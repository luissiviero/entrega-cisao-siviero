"""Figures for packet 1 (block rules) of companies 01 and 08.

Reads `planilha-mestre-01-08.xlsx` (generated by build_mestre_01_08.py) and
prints, for each proposed rule, the rows it covers, their totals and the
sample rows shown to Luís. No number in pacotes/pacote-01.md is typed by hand.

Usage: python -I pacote_01.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import openpyxl

sys.path.insert(0, str(Path(__file__).resolve().parent))
import extract_fase0 as fase0

WORK = Path(__file__).resolve().parents[1]
MASTER = WORK / "planilha-mestre-01-08.xlsx"
SAMPLE = ["08-2025-01", "08-2025-02", "08-2025-06", "08-2025-07", "08-2025-10"]


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    f = fase0.fmt
    ws = openpyxl.load_workbook(MASTER)["Mestre"]
    header = [c.value for c in ws[1]]
    rows = [
        dict(zip(header, r, strict=False))
        for r in ws.iter_rows(min_row=2, values_only=True)
    ]

    rules = {
        "R1": [r for r in rows if r["Situação"] == "Concorda"],
        "R2": [r for r in rows if r["Situação"] == "Não abordado — hoje na SEI"],
    }
    # the apartment donated in 2018 stays open in P4 (no deed): it goes to packet 2, not to a rule
    for rule, covered in rules.items():
        g = sum(r["Valor grupo 2025 (R$)"] or 0 for r in covered)
        raf = sum(r["Valor Rafael (R$)"] or 0 for r in covered)
        old = sum(r["Valor 2018 (R$)"] or 0 for r in covered)
        print(
            f"{rule}: {len(covered)} linhas; grupo 2025 {f(g)}; Rafael {f(raf)}; 2018 {f(old)}"
        )
        print("   " + ", ".join(r["ID"] for r in covered))

    print("Amostra R1:")
    for rid in SAMPLE:
        r = next(x for x in rows if x["ID"] == rid)
        assert r in rules["R1"], f"{rid} is not covered by R1"
        print(
            f"  {rid} | {r['Chave registral'][:40]} | grupo {f(r['Valor grupo 2025 (R$)'])} | Rafael {f(r['Valor Rafael (R$)'])} ({r['Página Rafael']}) | "
            f"2018 {f(r['Valor 2018 (R$)'])} ({r['Item 2018']}) | {r['Fonte 2025']}"
        )

    # Rovílio had 2 % of the 08 but no share of the 2018 Oficina and Agropecuária (six brothers, 16,666 % each)
    from_other = [
        r
        for r in rows
        if r["ID"].startswith("08-2025")
        and r["Item 2018"]
        and ("Oficina" in r["Item 2018"] or "Agropecuária" in r["Item 2018"])
    ]
    base = sum(r["Valor grupo 2025 (R$)"] for r in from_other)
    print(
        f"08: bens vindos da Oficina/Agropecuária de 2018: {', '.join(r['ID'] for r in from_other)} = {f(base)}; 2 % = {f(0.02 * base)}"
    )
    total08 = sum(
        r["Valor grupo 2025 (R$)"] or 0 for r in rows if r["ID"].startswith("08-2025")
    )
    print(
        f"   2 % do total da 08 = {f(0.02 * total08)}; parcela vinda de empresas sem Rovílio = {0.02 * base / (0.02 * total08) * 100:.1f} %"
    )

    rest = [r for r in rows if not any(r in c for c in rules.values())]
    print("Fora das regras (pacote 2, exceções, pelo maior valor):")
    for r in sorted(
        rest,
        key=lambda x: (
            -max(
                x["Valor grupo 2025 (R$)"] or 0,
                x["Valor Rafael (R$)"] or 0,
                x["Valor 2018 (R$)"] or 0,
            )
        ),
    ):
        print(
            f"  {r['ID']} | {r['Situação']} | grupo {f(r['Valor grupo 2025 (R$)'])} | Rafael {f(r['Valor Rafael (R$)'])} | 2018 {f(r['Valor 2018 (R$)'])}"
        )
    total_rows = sum(len(c) for c in rules.values()) + len(rest)
    print(f"linhas: {total_rows} (planilha {len(rows)})")


if __name__ == "__main__":
    main()
